// Writes src/server/pdf/pdf-assets.generated.ts — the stylesheet and fonts
// embedded in every server-generated PDF, so the PDF page loads nothing from
// the network.
//
//   npm run pdf:assets              stylesheet + fonts (fonts need network)
//   npm run pdf:assets -- --css-only  stylesheet only, keeps the embedded fonts
//
// Re-run after changing any component listed in PDF_SOURCES
// (scripts/pdf-stylesheet.mjs); pdf-assets.test.ts fails while it is stale.
import fs from "node:fs";
import path from "node:path";
import { buildPdfStylesheet } from "./pdf-stylesheet.mjs";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "src/server/pdf/pdf-assets.generated.ts");
// The three families the app loads through next/font (src/app/layout.tsx).
const FONTS_URL =
  "https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700&family=IBM+Plex+Mono:wght@400;600&family=Source+Serif+4:wght@500;600&display=block";
const BROWSER_UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36";

async function buildFontFaces() {
  const css = await (await fetch(FONTS_URL, { headers: { "user-agent": BROWSER_UA } })).text();
  const latin = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)].filter((m) => m[1] === "latin").map((m) => m[2]);
  if (latin.length === 0) throw new Error("No latin @font-face blocks returned by Google Fonts");
  const files = new Map();
  let out = "";
  for (const block of latin) {
    const url = /url\((https:[^)]+\.woff2)\)/.exec(block)?.[1];
    if (!url) throw new Error(`No woff2 source in ${block}`);
    if (!files.has(url)) files.set(url, Buffer.from(await (await fetch(url)).arrayBuffer()).toString("base64"));
    out += `${block.replace(url, `data:font/woff2;base64,${files.get(url)}`).replace(/\s+/g, " ")}\n`;
  }
  return out;
}

function existingFontFaces() {
  const text = fs.readFileSync(OUT, "utf8");
  const m = /export const PDF_FONT_FACES = (".*");/.exec(text);
  if (!m) throw new Error("No embedded fonts to keep — run without --css-only");
  return JSON.parse(m[1]);
}

const cssOnly = process.argv.includes("--css-only");
const [stylesheet, fonts] = await Promise.all([buildPdfStylesheet(ROOT), cssOnly ? existingFontFaces() : buildFontFaces()]);
fs.writeFileSync(
  OUT,
  `// GENERATED by scripts/build-pdf-assets.mjs — do not edit by hand.\n` +
    `// Regenerate with \`npm run pdf:assets\` after changing a component listed in scripts/pdf-stylesheet.mjs.\n\n` +
    `export const PDF_STYLESHEET = ${JSON.stringify(stylesheet)};\n\n` +
    `export const PDF_FONT_FACES = ${JSON.stringify(fonts)};\n`,
);
console.log(`Wrote ${path.relative(ROOT, OUT)} — stylesheet ${(stylesheet.length / 1024).toFixed(1)} KB, fonts ${(fonts.length / 1024).toFixed(1)} KB`);
